import pytest
from twttr import shorten

def test_general_string():
    assert shorten("twitter") == "twttr"
    assert shorten("CS50") == "CS50"

def test_upper():
    assert shorten("AEIOU") == ""

def test_lower():
    assert shorten("aeiou") == ""

def test_num():
    assert shorten("012345") == "012345"
    assert shorten("-1-2-3-4") == "-1-2-3-4"
    assert shorten("1.01.11.2-1.1-1.2") == "1.01.11.2-1.1-1.2"

def test_symbol():
    assert shorten("Hello, World!") == "Hll, Wrld!"
    assert shorten("How are you? I'm fine. Thank you!") == "Hw r y? 'm fn. Thnk y!"



