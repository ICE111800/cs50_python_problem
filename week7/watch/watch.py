import re
import sys


def main():
    print(parse(input("HTML: ")))


def parse(s: str) -> str | None:
    # 把所有支援的模式收納在一個清單中
    patterns = [
        r"<iframe\b[^>]*src=\"https?://(?:www\.)?youtube\.com/embed/([a-zA-Z0-9_-]+)\"",      # Embed 嵌入型
        r"<iframe\b[^>]*src=\"https?://youtu\.be/([a-zA-Z0-9_-]+)\"",                         # short 短網址
        r"<iframe\b[^>]*src=\"https?://(?:www\.)?youtube\.com/shorts/([a-zA-Z0-9_-]+)\"",     # shorts 短片型
        r"<iframe\b[^>]*src=\"https?://(?:www\.)?youtube\.com/watch\?v=([a-zA-Z0-9_-]+)\"",   # watch page 標準觀看型
    ]

    # 逐一嘗試每個模式
    for pattern in patterns:
        if matches := re.search(pattern, s, re.IGNORECASE):
            return f"https://youtu.be/{matches.group(1)}"
    
    return None

if __name__ == "__main__":
    main()



