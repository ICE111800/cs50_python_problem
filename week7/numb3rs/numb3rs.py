import re
import sys

# 定義常數
IPV4_OCTET_COUNT = 4
MAX_IPV4_VALUE = 255


def main():
    print(validate(input("IPv4 Address: ")))

def validate(ip: str) -> bool:
    """
    驗證輸入的字串是否為合法的 IPv4 位址。
    防禦重點：
      1. 嚴格邊界檢查（4個數字區段，不允許前後有多餘字元）。
      2. 前導零防禦（不允許像 '001' 或 '01' 的格式）。
      3. 數值範圍防禦（每個區段必須介於 0 到 255 之間）。
    """
    # 結構邊界檢查：確保剛好有 4 個數字區段以點分隔
    if matches := re.search(r"^([0-9]+)\.([0-9]+)\.([0-9]+)\.([0-9]+)$", ip):

        # 逐一巡訪每個區段進行數值與格式審查
        for i in range(IPV4_OCTET_COUNT):
            val_str = matches.group(i + 1)

            # 防禦：檢查前導零（例如長度大於 1 卻以 '0' 開頭，如 '01'）
            if val_str.startswith("0") and len(val_str) > 1:
                return False

            # 防禦：轉為整數並檢查是否在 0 ~ 255 範圍內
            if not (0 <= int(val_str) <= MAX_IPV4_VALUE):
                return False
            
        return True 
    
    # 如果正規表達式根本沒對應成功（如缺少區段、夾雜字母或符號），直接攔截
    return False

            
if __name__ == "__main__":
    main()



