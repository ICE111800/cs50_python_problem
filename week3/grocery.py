def main():
    # 宣告一個空的字典，用來記錄「物品名稱 (Key): 購買次數 (Value)」
    grocery = {}
    
    while True:
        try:
            item = input().strip().upper()
            # ==========================================
            # 【商業防呆：過濾空白輸入】
            # 用途：如果使用者什麼都沒打就按 Enter (item 變成空字串 "")
            # 我們用 not item 來檢查，如果是空的就跳過這輪，不計入清單。
            # ==========================================
            if not item:
                continue

        # ==========================================
        # 【例外處理 (Try-Except)】
        # 用途：處理「無法控制的系統級外部突發狀況」
        # 例如：使用者按下 Ctrl+D (EOFError)，代表輸入結束。
        # ==========================================
        except EOFError:
            # 當使用者按 Ctrl+D 時，開始把字典印出來
            # sorted(grocery) 會自動將字典的 Keys (物品名稱) 按字母順序排好
            for item in sorted(grocery):
                # 依序印出：次數(Value) + 空格 + 物品名稱(Key)
                print(f"{grocery[item]} {item}")
            break

        # ==========================================
        # 【字典計數神技 (Counter Pattern)】
        # 用途：累加物品出現的次數
        # grocery.get(item, 0)：去字典找這個物品，找不到就預設為 0
        # 然後 + 1，再存回 grocery[item] 裡面
        # ==========================================
        grocery[item] = grocery.get(item, 0) + 1
        
if __name__ == "__main__":
    main()

# =====================================================
# 【取值原理解析：為什麼 {grocery[item]} 是次數？】
# - for item in sorted(grocery)：迴圈每次拿出一把排好序的
#   「鑰匙 (Key)」，也就是物品名稱（例如 "APPLE"）。
# - {item}：直接印出這把鑰匙（物品名稱）。
# - {grocery[item]}：拿著這把鑰匙去 dictionary 查對應的
#   「數值 (Value)」，也就是我們存在裡面的購買次數！
# =====================================================

# =========================================================
# 【字典計數神技解析：grocery[item] = grocery.get(item, 0) + 1】
# 這行同時做了「查詢」與「設定」兩個動作：
# 1. 右邊的 grocery.get(item, 0)：
#    去字典找有沒有這個 item (Key)。
#    - 如果「找不到」（第一次輸入）：回傳你設定的預設值 0。
#    - 如果「找得到」（已經有紀錄）：回傳字典裡現有的次數。
# 2. + 1：把剛才查到的數字加 1。
# 3. 左邊的 grocery[item] = ...：
#    把算好的新數字存回（或更新）字典的該 item 裡面，
#    讓它變成新的 Value（例如從 0 變 1，或從 1 變 2）。
# =========================================================

"""
=========================================================
【詳細拆解：grocery[item] = grocery.get(item, 0) + 1】
=========================================================
    你可能會問：「我明明沒設定值給他，它是怎麼生出數字的？」
    其實，這行程式碼同時包含「查詢」與「設定/更新值」兩個動作。

    假設目前字典是空的：grocery = {}

---------------------------------------------------------
🎬 情況 A：你第一次輸入 "APPLE"
---------------------------------------------------------
    1. 使用者輸入了 "APPLE"，所以變數 item = "APPLE"。
    2. Python 會先看等號的右邊：
        - grocery.get("APPLE", 0)：去 grocery 字典找有沒有 "APPLE" 這把鑰匙 (Key)。
        - 因為現在字典是空的，找不到！.get() 於是吐出預設值 0。
    3. 進行加法：0 + 1 ＝ 1。
    4. 接著看等號的左邊：
        - grocery["APPLE"] = 1：這時候正式幫它設定值！
        - 把 "APPLE" 作為 Key，數字 1 作為 Value 存進字典。
        - 現在字典變成：{"APPLE": 1}

---------------------------------------------------------
🎬 情況 B：你第二次又輸入了 "APPLE"
---------------------------------------------------------
    1. 變數 item = "APPLE"。
    2. 看等號的右邊：
        - grocery.get("APPLE", 0)：這次去字典找，找到了！記錄的數值是 1。
        - .get() 這次吐出來的數字是 1（而不是預設的 0）。
    3. 進行加法：1 + 1 ＝ 2。
    4. 看等號的左邊：
        - grocery["APPLE"] = 2：把原本的 1 覆蓋更新成 2。
        - 現在字典變成：{"APPLE": 2}

    【總結】
    它不是「沒有設定值」，而是透過 grocery[item] = ... 
    主動去設定（或更新）了那個值！
=========================================================
"""