import re

# =============================================================================
# 【階段一】傳統字串檢查法（盲點百出）
# =============================================================================

# 1. 陽春版：只檢查有沒有 "@"
email = input("What's your email? ").strip()
if "@" in email:
    print("Valid")
else:
    print("Invalid")
# 缺陷：如果使用者只輸入 "@"，也會被判定為 Valid，條件太寬鬆。


# 2. 進階版：檢查 "@" 與 "." 同時存在
email = input("What's your email? ").strip()
if "@" in email and "." in email:
    print("Valid")
else:
    print("Invalid")
# 缺陷：如果使用者輸入 "@." 也能通過，但這絕對不是合法的信箱。


# 3. 切割版：用 split() 檢查 username 和 domain
email = input("What's your email? ").strip()
username, domain = email.split("@")
if username and "." in domain:
    print("Valid")
else:
    print("Invalid")
# 缺陷：條件開始變複雜，如果想更精準（例如限定 .edu 結尾），
# 程式碼會越寫越臃腫，難以維護。


# =============================================================================
# 【階段二】擁抱正則表達式（re 模組）
# =============================================================================

# 4. 初試啼見 re.search()
# re.search(pattern, string, flags=0) 用於在字串中搜尋符合模式的片段。
email = input("What's your email? ").strip()
if re.search("@", email):
    print("Valid")
else:
    print("Invalid")
# 缺點：這跟用 "@" in email 沒兩樣，我們需要更強大的特殊符號（Pattern）。


# 5. 結合特殊符號 (.* 和 .+)
# .  : 除了換行符號外的任意字元
# *  : 0次或多次重複
# +  : 1次或多次重複
email = input("What's your email? ").strip()

# 模式 ".*@.+" 代表：@ 左邊可以有任意多個字元(*)，@ 右邊必須至少有一個字元(+)
if re.search(".*@.+", email):
    print("Valid")
else:
    print("Invalid")


# 6. 最終階段：精準鎖定以 .edu 結尾
email = input("What's your email? ").strip()

# 模式 ".+@.+.edu" 代表：@ 左邊至少1個字元，@ 與 .edu 之間至少1個字元，且結尾是 .edu
if re.search(".+@.+.edu", email):
    print("Valid")
else:
    print("Invalid")



# =============================================================================
# 【階段三】解決漏洞與精準對齊
# =============================================================================

# 1. 解決 "." 的萬用漏洞（加入跳脫字元 \ 與 Raw String r""）
# 漏洞：原本的 .edu 會讓 "harvard?edu" 也能過關。
# 解決：用 \. 代表「真正的點號」，並在字串前加 r 宣告為原始字串 (Raw String)，
# 避免 Python 把 \ 當成特殊轉譯序列（例如 \n）。
email = input("What's your email? ").strip()
if re.search(r".+@.+\.edu", email):
    print("Valid")
else:
    print("Invalid")


# 2. 引入錨點 ^ 與 $（全字串精準匹配）
# 漏洞：只要字串「中間」包含符合的片段就會過（例如輸入長篇大論包著信箱）。
# 解決：^ 代表字串開頭，$ 代表字串結尾。整個字串必須完全符合該模式。
email = input("What's your email? ").strip()
if re.search(r"^.+@.+\.edu$", email):
    print("Valid")
else:
    print("Invalid")


# 3. 使用方括號 [] 與補集 [^]（限制字元範圍）
# 漏洞：使用者可以輸入 "ice@@@harvard.edu"，因為 . 太寬鬆了。
# 解決：[^@] 代表「除了 @ 之外的任意字元」，防止重複輸入 @。
email = input("What's your email? ").strip()
if re.search(r"^[^@]+@[^@]+\.edu$", email):
    print("Valid")
else:
    print("Invalid")


# 4. 指定明確的字元範圍 [a-zA-Z0-9_]
# 漏洞：[^@] 還是允許了像問號、空格等怪異符號。
# 解決：用連字符 - 定義明確的白名單（大小寫英文、數字、底線）。
email = input("What's your email? ").strip()
if re.search(r"^[a-zA-Z0-9_]+@[a-zA-Z0-9_]+\.edu$", email):
    print("Valid")
else:
    print("Invalid")


# 5. 終極精簡版：使用 Shorthand 簡寫字元 (\w)
# 概念：[a-zA-Z0-9_] 太長了，Python 提供簡寫 \w (Word character) 來代表牠們。
email = input("What's your email? ").strip()
if re.search(r"^\w+@\w+\.edu$", email):
    print("Valid")
else:
    print("Invalid")



# =============================================================================
# 【階段四】處理多種頂級網域 (Alternation |)
# =============================================================================
# 漏洞：原本限制死只能是 .edu。
# 解決：用管道符 | 代表 OR，並用括號 () 進行分組。
email = input("What's your email? ").strip()
if re.search(r"^\w+@\w+\.(com|edu|gov|net|org)$", email, re.IGNORECASE):
    print("Valid")
else:
    print("Invalid")


# =============================================================================
# 【階段五】處理大小寫敏感問題 (re.IGNORECASE)
# =============================================================================
# 問題：輸入 "ICE@HARVARD.EDU" 會被判定 Invalid，儘管 \w 支援大小寫，但 .EDU 的點號或格式會有影響。
# 解決方法 1：在 python 程式碼中用 .lower() 轉小寫
# 解決方法 2：直接使用 re.search 的第三個參數 flags -> re.IGNORECASE
email = input("What's your email? ").strip()
if re.search(r"^\w+@\w+\.edu$", email, re.IGNORECASE):
    print("Valid")
else:
    print("Invalid")


# =============================================================================
# 【階段六】處理子網域 (Subdomains) 與選擇性符號 (?)
# =============================================================================
# 問題：輸入 "ice@cs50.harvard.edu" 會失敗，因為多了一個 "cs50."。
# 暴力解法：寫成 \w+\.\w+\.\w+\.edu，但這會導致原本的 "ice@harvard.edu" 變成 Invalid。
# 最終解法：利用問號 ? 代表「0 次或 1 次重複（選擇性）」，並將子網域組括號起來：(\w+\.)?
email = input("What's your email? ").strip()
if re.search(r"^\w+@(\w+\.)?\w+\.edu$", email, re.IGNORECASE):
    print("Valid")
else:
    print("Invalid")
# 效果：
# - 支援 "ice@harvard.edu"（子網域出現 0 次）
# - 支援 "ice@cs50.harvard.edu"（子網域出現 1 次）



# =============================================================================
# 【階段七】處理多重子網域與群組量詞
# =============================================================================
# - 透過 (\w+\.)? 讓單個子網域變成選擇性（0次或1次）。
# - 如果要允許「多個」子網域，可以將其改為 (\w+\.)*。
email = input("What's your email? ").strip()
if re.search(r"^\w+@(\w+\.)?\w+\.edu$", email, re.IGNORECASE):
    print("Valid")
else:
    print("Invalid")


# =============================================================================
# 【階段八】re 模組的其他實用函數：match 與 fullmatch
# =============================================================================
# 1. re.match()     : 預設自動從字串「開頭」開始匹配（不用加 ^）。
# 2. re.fullmatch() : 自動同時匹配「開頭與結尾」（^ 和 $ 都不用加了，最嚴格）。
# 範例：以下兩行效果完全相同
# re.search(r"^\w+@\w+\.edu$", email)
# re.fullmatch(r"\w+@\w+\.edu", email)


# =============================================================================
# 【階段九】現實世界的數據清理 (Data Cleaning / format.py)
# =============================================================================
# 情境：面對不按牌理出牌的使用者（例如把名字寫成 "Malan, David"），
# 系統需要將其標準化調整為 "David Malan"。

name = input("What's your name? ").strip()

# 傳統 Python 字串方法的侷限：字串自帶的 .split() 不支援正則表達式，
# 無法優雅地處理「可有可無的空格（如 ", ?"）」。

# 終極解法：使用 re.search() 配合「捕獲群組 (Capture Groups)」
# 語法解釋：
# - r"^(.+), (.+)$"：
#   - 第一個括號 (1組)：捕獲名字前半部 (last name)
#   - 第二個括號 (2組)：捕獲名字後半部 (first name)
matches = re.search(r"^(.+), (.+)$", name)

if matches:
    # matches.groups() 會回傳一個包含所有括號捕獲內容的 tuple
    # 或者透過 matches.group(1) 與 matches.group(2) 精準取得特定分組
    last, first = matches.groups()
    name = f"{first} {last}"

print(f"hello, {name}")



# =============================================================================
# 【階段十】群組索引與海象運算符 (Walrus Operator :=)
# =============================================================================

# 1. 處理空格與捕獲群組索引
# matches.group(0) 代表整行匹配到的字串；group(1)、group(2) 依序對應括號。
# 為了相容使用者輸入大量空格（如 "Malan,     David"），用 * 取代 ?
name = input("What's your name? ").strip()
if matches := re.search(r"^(.+), *(.+)$", name):
    # 海象運算符 := 可以在判斷式內同時完成「賦值」與「Boolean 檢查」，簡化程式碼
    name = matches.group(2) + " " + matches.group(1)

print(f"hello, {name}")


# =============================================================================
# 【階段十一】字串清理：從簡單 replace 到 re.sub()
# =============================================================================

# 1. 傳統字串方法：replace() 與 removeprefix()
# 缺點：不夠靈活，無法應對 http/https、有無 www. 或大小寫混雜的複雜情況。
url = input("URL: ").strip()
username = url.removeprefix("https://twitter.com/")


# 2. 進階字串取代：re.sub(pattern, repl, string)
# 用正則表達式把匹配到的前綴直接替換成空字串 ""
# s?：字母 s 出現 0 次或 1 次（相容 http 與 https）。
# ?（在括號外面）：代表整個 (https?://) 群組出現 0 次或 1 次（選填，有沒有輸入都算符合）。
url = input("URL: ").strip()
username = re.sub(r"^(https?://)?(www\.)?twitter\.com/", "", url)


# =============================================================================
# 【階段十二】終極版 Twitter 網址解析（結合 search、非捕獲群組與白名單）
# =============================================================================
# 需求：
# 1. 兼容 http / https (https?)
# 2. 兼容有無 www.，但又不需要捕獲它 -> 使用非捕獲群組 (?:www\.)?
# 3. 嚴格限制使用者名稱只允許英數字與底線 [a-z0-9_]+，排除多餘的斜槓或參數。
url = input("URL: ").strip()

if matches := re.search(r"^https?://(?:www\.)?twitter\.com/([a-z0-9_]+)", url, re.IGNORECASE):
    print(f"Username:", matches.group(1))
else:
    print("Invalid URL")

