import re

url = "https://www.twitter.com/my_name123"

# 狀況 A：如果把 www 也設成一般捕獲群組 -> (www\.)?([a-z0-9_]+)
# match.group(1) 會抓到 "www."
# match.group(2) 才會抓到 "my_name123" （會亂掉！）

# 狀況 B：使用非捕獲群組 -> (?:www\.)?([a-z0-9_]+)
